def ffmpeg_bin() -> str:
    exe = shutil.which("ffmpeg")
    if exe:
        return exe
    try:
        import imageio_ffmpeg  # type: ignore
    except ImportError:
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "imageio-ffmpeg"], check=True
        )
        import imageio_ffmpeg  # type: ignore
    return imageio_ffmpeg.get_ffmpeg_exe()


def duration_s(ffmpeg: str, mp4: Path) -> float:
    out = subprocess.run(
        [ffmpeg, "-hide_banner", "-i", str(mp4)],
        capture_output=True,
        text=True,
    ).stderr
    m = re.search(r"Duration: (\d+):(\d+):([\d.]+)", out)
    if not m:
        raise RuntimeError(f"can't read duration of {mp4.name}")
    h, mnt, s = int(m.group(1)), int(m.group(2)), float(m.group(3))
    return h * 3600 + mnt * 60 + s


def fmt_dur(s: float) -> str:
    r = round(s, 1)
    return f"{int(r)} s" if r == int(r) else f"{r} s"


def fmt_size(n: int) -> str:
    mb = n / 1_000_000
    return f"{mb:.1f} MB" if mb < 100 else f"{mb:.0f} MB"


def slugify(stem: str) -> str:
    s = stem.removeprefix("bitcoin-shipshow-short-").removeprefix("bitcoin-shipshow-")
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or stem


def titleize(slug: str) -> str:
    return re.sub(r"[-_]+", " ", slug).title()


def main() -> None:
    mp4s = sorted(VIDEOS.glob("*.mp4"))
    if not mp4s:
        sys.exit("no MP4s found in site/videos/ — nothing to build")
    ffmpeg = ffmpeg_bin()
    POSTERS.mkdir(parents=True, exist_ok=True)

    cards, wanted_posters = [], set()
    for i, mp4 in enumerate(mp4s):
        meta = dict(SHORTS.get(mp4.name, {}))
        slug = slugify(mp4.stem)
        dur = duration_s(ffmpeg, mp4)
        poster_at = meta.get("poster_at", dur * 0.3)
        poster = POSTERS / f"{slug}.jpg"
        wanted_posters.add(poster.name)
        subprocess.run(
            [
                ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
                "-ss", str(poster_at), "-i", str(mp4),
                "-frames:v", "1", "-q:v", "4", str(poster),
            ],
            check=True,
        )
        cards.append(
            (
                meta.get("order", 1000 + i),
                CARD.format(
                    file=mp4.name,
                    slug=slug,
                    title=escape(meta.get("title", titleize(slug))),
                    tag=escape(meta.get("tag", "Reusable")),
                    desc=escape(meta.get("desc", "Promo short for the Bitcoin Shipshow — preview and download to repost.")),
                    specs=escape(f"{fmt_dur(dur)} · 16:9" + (f" · {meta['specs']}" if meta.get("specs") else "")),
                    size=fmt_size(mp4.stat().st_size),
                ),
            )
        )
        print(f"  {mp4.name}: {fmt_dur(dur)}, poster @ {poster_at}s")

    for stale in POSTERS.glob("*.jpg"):
        if stale.name not in wanted_posters:
            stale.unlink()
            print(f"  removed stale poster {stale.name}")

    cards = [c for _, c in sorted(cards, key=lambda x: x[0])]
    (SITE / "shorts.html").write_text(
        PAGE_HEAD.replace("{count}", str(len(mp4s))).replace("{cards}", "".join(cards))
    )
    (SITE / "shorts.css").write_text(SHORTS_CSS)

    index = SITE / "index.html"
    html = index.read_text()
    if 'href="shorts"' not in html and 'href="/shorts"' not in html:
        anchor = '<p class="toolbar__count"'
        idx = html.find(anchor)
        if idx == -1:
            sys.exit("index.html: couldn't find toolbar__count anchor for nav link")
        html = html[:idx] + NAV_LINK + "    " + html[idx:]
        index.write_text(html)
        print("  patched index.html with the nav link")

    css = SITE / "styles.css"
    text = css.read_text()
    if ".tab--cta" not in text:
        marker = ".tab input:checked + span"
        line_end = text.find("\n", text.find(marker))
        text = text[: line_end + 1] + CTA_CSS + text[line_end + 1 :]
        css.write_text(text)
        print("  appended .tab--cta rules to styles.css")

    print(f"built shorts page: {len(mp4s)} videos")


if __name__ == "__main__":
    main()
